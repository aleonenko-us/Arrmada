// Command gen writes internal/langs/table_gen.go from the vendored iso639.tsv beside it.
// It is run by `go generate ./internal/langs` (from the package directory) and never by the
// build: the table is committed, so nothing at build or run time reads the TSV or touches
// the network.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

func main() {
	in, out := "gen/iso639.tsv", "table_gen.go"
	if len(os.Args) == 3 {
		in, out = os.Args[1], os.Args[2]
	}
	f, err := os.Open(in)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/langs/gen from gen/iso639.tsv; DO NOT EDIT.\n\n")
	b.WriteString("package langs\n\n")
	b.WriteString("var table = []Language{\n")
	seen := map[string]int{}
	iso2 := map[string][2]string{}
	sc := bufio.NewScanner(f)
	for n := 1; sc.Scan(); n++ {
		line := sc.Text()
		if strings.TrimSpace(line) == "" || strings.HasPrefix(line, "#") {
			continue
		}
		cols := strings.Split(line, "\t")
		if len(cols) != 6 {
			log.Fatalf("%s:%d: want 6 tab-separated columns, got %d", in, n, len(cols))
		}
		for i := range cols {
			cols[i] = strings.TrimSpace(cols[i])
			if cols[i] == "-" {
				cols[i] = ""
			}
		}
		code, b2, t2, name, aliases, osub := cols[0], cols[1], cols[2], cols[3], cols[4], cols[5]
		if code == "" || name == "" || code != strings.ToLower(code) {
			log.Fatalf("%s:%d: code must be lower case and the name set", in, n)
		}
		base, region, regional := strings.Cut(code, "-")
		if len(base) != 2 || (regional && region == "") {
			log.Fatalf("%s:%d: %q is not a 639-1 code or <639-1>-<region> tag", in, n, code)
		}
		if !regional && (len(b2) != 3 || len(t2) != 3) {
			log.Fatalf("%s:%d: %s needs both 639-2 codes", in, n, code)
		}
		if regional {
			if _, ok := seen[base]; !ok {
				log.Fatalf("%s:%d: regional %s comes before (or without) its base %s", in, n, code, base)
			}
			// A regional variant is written with its base language's 639-2 codes.
			b2, t2 = iso2[base][0], iso2[base][1]
		} else {
			iso2[code] = [2]string{b2, t2}
		}
		if prev, dup := seen[code]; dup {
			log.Fatalf("%s:%d: %s already defined on line %d", in, n, code, prev)
		}
		seen[code] = n
		var al []string
		if aliases != "" {
			for _, a := range strings.Split(aliases, ",") {
				if a = strings.TrimSpace(a); a != "" {
					al = append(al, a)
				}
			}
		}
		alSrc := "nil"
		if len(al) > 0 {
			alSrc = fmt.Sprintf("%#v", al)
		}
		fmt.Fprintf(&b, "\t{Code: %q, Name: %q, ISO1: %q, ISO2B: %q, ISO2T: %q, Regional: %v, aliases: %s, openSubs: %q},\n",
			code, name, base, b2, t2, regional, alSrc, osub)
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("format: %v\n%s", err, b.String())
	}
	if err := os.WriteFile(out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
