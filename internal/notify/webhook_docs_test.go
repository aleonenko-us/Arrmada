package notify

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// The event reference in docs/n8n.md is written from webhook_events.go, so the two can't
// drift: this fails when they differ, and -update rewrites the section between the markers.

const (
	docsBegin = "<!-- BEGIN EVENT REFERENCE: generated by `go test ./internal/notify -run TestWebhookDocsUpToDate -update` -->"
	docsEnd   = "<!-- END EVENT REFERENCE -->"
)

func eventReference() string {
	var b strings.Builder
	groupLabel := map[string]string{}
	for _, g := range Groups() {
		groupLabel[g.Key] = g.Label
	}
	group := ""
	for _, def := range Catalog() {
		if def.Group != group {
			group = def.Group
			fmt.Fprintf(&b, "\n### %s\n", groupLabel[group])
		}
		spec := webhookEvents[def.Key]
		sev := spec.severity
		if sev == "" {
			sev = "info"
		}
		if levelSeverity[def.Key] {
			sev += " (or the item's level)"
		}
		fmt.Fprintf(&b, "\n#### `%s` — %s\n\n%s Severity: %s.", def.Key, def.Label, def.Hint, sev)
		if def.Module != "" {
			fmt.Fprintf(&b, " Only while the %s module is on.", def.Module)
		}
		b.WriteString("\n\n| Field | Type | Meaning |\n|---|---|---|\n")
		for _, f := range spec.fields {
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", f.Name, f.Type, strings.ReplaceAll(f.Doc, "|", "\\|"))
		}
	}
	return b.String()
}

func TestWebhookDocsUpToDate(t *testing.T) {
	path := filepath.Join("..", "..", "docs", "n8n.md")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	doc := strings.ReplaceAll(string(raw), "\r\n", "\n")
	i, j := strings.Index(doc, docsBegin), strings.Index(doc, docsEnd)
	if i < 0 || j < i {
		t.Fatalf("docs/n8n.md has no event reference markers")
	}
	want := doc[:i+len(docsBegin)] + "\n" + eventReference() + "\n" + doc[j:]
	if want == doc {
		return
	}
	if *updateGolden {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	t.Fatalf("docs/n8n.md's event reference is out of date; run go test ./internal/notify -run TestWebhookDocsUpToDate -update")
}
